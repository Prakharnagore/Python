import math

print(round(2.9))  # print 3
print(abs(-2.9))  # print 2.9
print(10 > 3)  # print True


print(math.ceil(2.2))  # round up to the nearest integer
print(math.floor(2.3))  # round down to the nearest integer
print(math.pi)  # 3.141592653589793
print(math.e)  # 2.718281828459045
print(math.sqrt(16))  # return the square root of 16
print(math.pow(2, 3))  # return 2 raised to the power of 3
print(math.log(10))  # return the natural logarithm of 10
print(math.log10(10))  # return the base 10 logarithm of 10
print(math.log2(10))  # return the base 2 logarithm of 10
print(math.log1p(10))  # return the natural logarithm of 1 plus 10
