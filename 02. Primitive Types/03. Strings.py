message = """Hello World
This is a multi-line string"""

print(len(message))
print(message[0])
print(message[-1])  # return the last character of the string
# return copy of the string from index 0 to 5 (not including index 5)
print(message[0:5])
# return copy of the string from index 0 to end (not including index 0)
print(message[0:])
# return copy of the string from index 0 to end (not including index 0)
print(message[:])
# return copy of the string start till index 3 (not including index 3)
print(message[:3])
