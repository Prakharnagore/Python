# To install a package from PyPI, we use the pip command.

# to install a package
# pip3 install <package-name>

# to upgrade a package
# pip3 install --upgrade <package-name>

# to list all the packages installed
# pip3 list

# to install a package from a specific version
# pip3 install <package-name>==<version>

# install latest compatible version of a package
# pip3 install <package-name>=2.9.*
# pip3 install <package-name>~=2.9

# to uninstall a package
# pip3 uninstall <package-name>
